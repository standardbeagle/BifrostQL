using System.Net.Http.Headers;
using System.Text;
using System.Text.Json;
using BifrostQL.Core.Model;
using BifrostQL.Ngsql;
using BifrostQL.Server;
using FluentAssertions;
using Microsoft.AspNetCore.Builder;
using Microsoft.AspNetCore.Hosting;
using Microsoft.AspNetCore.TestHost;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Hosting;
using Npgsql;

namespace BifrostQL.Integration.Test;

/// <summary>
/// Runs the exact HTTP bodies <c>useBifrostBatch</c> sends against a real PostgreSQL server on the
/// bulk fast path, which the SQLite wire contract tests cannot reach. Two probes tell the paths apart
/// from outside: a statement-level trigger records the rows each write statement touched, and an
/// event trigger records the staging table only the fast path creates.
/// </summary>
public sealed class ReactBatchPostgresBulkContractTests : IAsyncLifetime
{
    private const string SeedTenThousand =
        "INSERT INTO items (id, sku, name) SELECT n, 'seed-' || n, 'seed' FROM generate_series(1000, 10999) n";

    private const string FastPath = "1";
    private const string PerRow = "0";

    private static readonly string ContractPath = Path.Combine(
        AppContext.BaseDirectory, "Fixtures", "batch-wire-contract.json");

    private static string? Master => Environment.GetEnvironmentVariable("BIFROST_TEST_POSTGRES");

    private string _dbName = null!;
    private string _connectionString = null!;

    public async Task InitializeAsync()
    {
        if (Master is null) return;
        _dbName = $"bifrost_react_bulk_{Guid.NewGuid():N}";
        await ExecAsync(Master, $"CREATE DATABASE \"{_dbName}\"");
        _connectionString = new NpgsqlConnectionStringBuilder(Master) { Database = _dbName }.ConnectionString;
        await ExecAsync(_connectionString,
            """
            CREATE TABLE items (id INT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY, sku VARCHAR(50) NOT NULL UNIQUE, name VARCHAR(50) NOT NULL, parent_id INT REFERENCES items (id));
            CREATE TABLE write_statements (id SERIAL PRIMARY KEY, verb TEXT NOT NULL, row_count INT NOT NULL);
            CREATE FUNCTION record_write_statement() RETURNS trigger LANGUAGE plpgsql AS $$
            BEGIN
                INSERT INTO write_statements (verb, row_count) SELECT TG_ARGV[0], COUNT(*) FROM changed;
                RETURN NULL;
            END $$;
            CREATE TRIGGER record_insert_statement AFTER INSERT ON items
                REFERENCING NEW TABLE AS changed FOR EACH STATEMENT EXECUTE FUNCTION record_write_statement('I');
            CREATE TRIGGER record_update_statement AFTER UPDATE ON items
                REFERENCING NEW TABLE AS changed FOR EACH STATEMENT EXECUTE FUNCTION record_write_statement('U');
            CREATE TRIGGER record_delete_statement AFTER DELETE ON items
                REFERENCING OLD TABLE AS changed FOR EACH STATEMENT EXECUTE FUNCTION record_write_statement('D');
            CREATE TABLE staging_tables (id SERIAL PRIMARY KEY, created_at TIMESTAMPTZ NOT NULL DEFAULT now());
            CREATE FUNCTION record_staging_table() RETURNS event_trigger LANGUAGE plpgsql AS $$
            BEGIN
                INSERT INTO staging_tables DEFAULT VALUES;
            END $$;
            CREATE EVENT TRIGGER record_staging_table ON ddl_command_end WHEN TAG IN ('CREATE TABLE AS')
                EXECUTE FUNCTION record_staging_table();
            """);
    }

    public async Task DisposeAsync()
    {
        if (Master is null) return;
        NpgsqlConnection.ClearAllPools();
        await ExecAsync(Master, $"DROP DATABASE IF EXISTS \"{_dbName}\" WITH (FORCE)");
    }

    [SkippableFact]
    public async Task BulkDocument_TakesTheFastPath_AndMatchesThePerRowOutcome()
    {
        Skip.If(Master is null, "BIFROST_TEST_POSTGRES environment variable not set");
        using var contract = JsonDocument.Parse(await File.ReadAllTextAsync(ContractPath));
        var bulk = contract.RootElement.GetProperty("bulk");

        var fast = await RunAsync(bulk.GetProperty("request"), FastPath);
        var perRow = await RunAsync(bulk.GetProperty("request"), PerRow);

        fast.Reply.Should().Contain($"\"items_batch\":{bulk.GetProperty("reply").GetProperty("data").GetProperty("items_batch").GetInt32()}");
        fast.WriteStatements.Should().Equal(new[] { "I2", "U1", "D1" }, "the fast path writes both inserts in one statement");
        perRow.WriteStatements.Should().Equal(new[] { "I1", "I1", "U1", "D1" }, "the per-row loop writes one statement per insert");
        fast.Rows.Should().Equal(perRow.Rows);
        fast.Rows.Should().Equal("1|sku-1|renamed", "2|sku-2|two", "100|sku-a|a", "101|sku-b|b");
    }

    /// <summary>
    /// The differential behind the docs' "same outcome" claim: each document depends on the order of
    /// its rows, so a fast path that reordered them would refuse it or land different rows.
    /// </summary>
    [SkippableTheory]
    [InlineData("insertDeleteInsert")]
    [InlineData("deleteThenInsert")]
    public async Task ContractDocument_MatchesThePerRowOutcome(string document)
    {
        Skip.If(Master is null, "BIFROST_TEST_POSTGRES environment variable not set");
        using var contract = JsonDocument.Parse(await File.ReadAllTextAsync(ContractPath));
        var request = contract.RootElement.GetProperty(document).GetProperty("request");

        await AssertBothPathsAgreeAsync(request);
    }

    [SkippableFact]
    public async Task InsertDeleteInsert_AppliesTheLaterInsertAfterTheDelete()
    {
        Skip.If(Master is null, "BIFROST_TEST_POSTGRES environment variable not set");
        using var contract = JsonDocument.Parse(await File.ReadAllTextAsync(ContractPath));
        var request = contract.RootElement.GetProperty("insertDeleteInsert").GetProperty("request");

        var fast = await RunAsync(request, FastPath);

        fast.WriteStatements.Should().Equal("I1", "D1", "I1");
        fast.Rows.Should().Equal("1|sku-1|one", "2|sku-2|two", "100|sku-x|x", "101|sku-3|y");
    }

    [SkippableFact]
    public async Task UpdateThatFreesAValue_ThenInsertThatReusesIt_MatchesThePerRowOutcome()
    {
        Skip.If(Master is null, "BIFROST_TEST_POSTGRES environment variable not set");

        var fast = await AssertBothPathsAgreeAsync(BatchRequest(
            new { insert = new { sku = "sku-a", name = "a" } },
            new { update = new { sku = "sku-moved", id = 1 } },
            new { insert = new { sku = "sku-1", name = "reuses the moved value" } },
            new { delete = new { id = 2 } },
            new { insert = new { sku = "sku-2", name = "reuses the deleted value" } }));

        fast.WriteStatements.Should().Equal("I1", "U1", "I1", "D1", "I1");
    }

    /// <summary>
    /// The semantics the two paths do not share. A foreign key is checked at the end of a statement,
    /// and a run of rows is one statement on the fast path and one statement per row on the per-row
    /// path, so rows that only satisfy the key together pass the one and are refused by the other.
    /// Nothing is left violating the key either way. Pinned so the docs' "same semantics" stays
    /// honest about this exception, and so a change that closes it has to say so.
    /// </summary>
    [SkippableFact]
    public async Task RowsThatSatisfyAForeignKeyOnlyTogether_PassAsOneRun_ButNotRowByRow()
    {
        Skip.If(Master is null, "BIFROST_TEST_POSTGRES environment variable not set");

        var childThenParent = BatchRequest(
            new { insert = new { sku = "child", name = "child", parent_id = 101 } },
            new { insert = new { sku = "parent", name = "parent", parent_id = (int?)null } });
        await AssertPerRowRefusesWhatTheFastPathAppliesAsync(childThenParent, null, expectedRows: 5);

        const string family = "INSERT INTO items (id, sku, name) VALUES (21, 'parent', 'parent'); " +
                              "INSERT INTO items (id, sku, name, parent_id) VALUES (20, 'child', 'child', 21);";
        var parentThenChild = BatchRequest(new { delete = new { id = 21 } }, new { delete = new { id = 20 } });
        await AssertPerRowRefusesWhatTheFastPathAppliesAsync(parentThenChild, family, expectedRows: 3);
    }

    private async Task AssertPerRowRefusesWhatTheFastPathAppliesAsync(
        JsonElement request, string? extraSeed, int expectedRows)
    {
        var seeded = (await RunAsync(BatchRequest(), PerRow, extraSeed)).Rows;

        var perRow = await RunAsync(request, PerRow, extraSeed);
        perRow.Reply.Should().Contain("DATABASE_ERROR");
        perRow.Rows.Should().Equal(seeded, "the refused document writes nothing");

        var fast = await RunAsync(request, FastPath, extraSeed);
        fast.StagingTables.Should().Be(1);
        fast.Reply.Should().NotContain("\"errors\"");
        fast.Rows.Should().HaveCount(expectedRows);
    }

    /// <summary>
    /// What alternating verbs cost now that order is kept. Each change of verb is another statement,
    /// so a batch within the cap writes one statement per run, and a batch past it is the per-row loop.
    /// </summary>
    [SkippableFact]
    public async Task AlternatingVerbs_WriteOneStatementPerRun_AndFallBackPastTheCap()
    {
        Skip.If(Master is null, "BIFROST_TEST_POSTGRES environment variable not set");

        var withinCap = await RunAsync(BatchRequest(Alternating(rows: 8)), FastPath);
        withinCap.StagingTables.Should().Be(1, "eight runs fit the statement cap");
        withinCap.WriteStatements.Should().HaveCount(8);

        var pastCap = await RunAsync(BatchRequest(Alternating(rows: 100)), FastPath);
        pastCap.StagingTables.Should().Be(0, "a hundred runs do not, so the per-row loop takes the batch");
        pastCap.WriteStatements.Should().HaveCount(100);
        pastCap.Rows.Should().HaveCount(3 + 50 - 3, "fifty inserts, and only three of the fifty deletes find a row");
    }

    [SkippableTheory]
    [InlineData("insert")]
    [InlineData("update")]
    [InlineData("delete")]
    public async Task TenThousandRowsOfOneVerb_StayOneStatement(string verb)
    {
        Skip.If(Master is null, "BIFROST_TEST_POSTGRES environment variable not set");
        var ids = Enumerable.Range(1_000, 10_000).ToList();
        object[] actions = verb switch
        {
            "insert" => ids.Select(id => (object)new { insert = new { sku = $"new-{id}", name = "n" } }).ToArray(),
            "update" => ids.Select(id => (object)new { update = new { name = "renamed", id } }).ToArray(),
            _ => ids.Select(id => (object)new { delete = new { id } }).ToArray(),
        };

        var fast = await RunAsync(BatchRequest(actions), FastPath, verb == "insert" ? null : SeedTenThousand);

        fast.Reply.Should().Contain("\"items_batch\":10000");
        fast.StagingTables.Should().Be(1);
        fast.WriteStatements.Should().Equal($"{char.ToUpperInvariant(verb[0])}10000");
    }

    private async Task<Outcome> AssertBothPathsAgreeAsync(JsonElement request)
    {
        var perRow = await RunAsync(request, PerRow);
        var fast = await RunAsync(request, FastPath);

        perRow.StagingTables.Should().Be(0);
        fast.StagingTables.Should().Be(1, "the differential only means something if the fast path ran");
        perRow.Reply.Should().NotContain("\"errors\"");
        fast.Reply.Should().Be(perRow.Reply);
        fast.Rows.Should().Equal(perRow.Rows);
        return fast;
    }

    private static object[] Alternating(int rows)
        => Enumerable.Range(0, rows)
            .Select(i => i % 2 == 0
                ? (object)new { insert = new { sku = $"alt-{i}", name = "alt" } }
                : new { delete = new { id = i / 2 + 1 } })
            .ToArray();

    private static JsonElement BatchRequest(params object[] actions)
        => JsonSerializer.SerializeToElement(new
        {
            query = "mutation Batch($actions: [batch_items!]!) { items_batch(actions: $actions) }",
            variables = new { actions },
        });

    private sealed record Outcome(
        string Reply, IReadOnlyList<string> WriteStatements, int StagingTables, IReadOnlyList<string> Rows);

    private async Task<Outcome> RunAsync(JsonElement request, string bulkThreshold, string? extraSeed = null)
    {
        await ExecAsync(_connectionString,
            """
            TRUNCATE items RESTART IDENTITY;
            INSERT INTO items (id, sku, name) VALUES (1, 'sku-1', 'one'), (2, 'sku-2', 'two'), (3, 'sku-3', 'three');
            """);
        if (extraSeed is not null)
            await ExecAsync(_connectionString, extraSeed);
        await ExecAsync(_connectionString, "TRUNCATE write_statements; TRUNCATE staging_tables;");

        var config = new ConfigurationBuilder().AddInMemoryCollection(new Dictionary<string, string?>
        {
            ["Bifrost:DisableAuth"] = "true",
            ["Bifrost:Path"] = "/graphql",
            ["Bifrost:Metadata:0"] = $"public.items {{ bulk-batch-threshold: {bulkThreshold} }}",
            ["Bifrost:Metadata:1"] = "public.items { batch-max-size: 10000 }",
        }).Build();
        DbConnFactoryResolver.Register(BifrostDbProvider.PostgreSql, connectionString => new PostgresDbConnFactory(connectionString));
        using var host = await new HostBuilder().ConfigureWebHost(web =>
        {
            web.UseTestServer();
            web.ConfigureServices(services =>
            {
                services.AddRouting();
                services.AddBifrostQL(options => options
                    .BindConfiguration(config.GetSection("Bifrost"))
                    .BindConnectionString(_connectionString)
                    .BindProvider("postgres"));
            });
            web.Configure(app => app.UseBifrostQL());
        }).StartAsync();
        using var client = host.GetTestClient();

        using var content = new StringContent(request.GetRawText(), Encoding.UTF8);
        content.Headers.ContentType = new MediaTypeHeaderValue("application/json");
        using var response = await client.PostAsync("/graphql", content);
        var reply = await response.Content.ReadAsStringAsync();

        return new Outcome(
            reply,
            await ReadAsync("SELECT verb, row_count FROM write_statements ORDER BY id", reader => $"{reader.GetString(0)}{reader.GetInt32(1)}"),
            (await ReadAsync("SELECT COUNT(*) FROM staging_tables", reader => (int)reader.GetInt64(0))).Single(),
            await ReadAsync("SELECT id, sku, name FROM items ORDER BY id", reader => $"{reader.GetInt32(0)}|{reader.GetString(1)}|{reader.GetString(2)}"));
    }

    private async Task<List<T>> ReadAsync<T>(string sql, Func<NpgsqlDataReader, T> project)
    {
        await using var conn = new NpgsqlConnection(_connectionString);
        await conn.OpenAsync();
        await using var cmd = new NpgsqlCommand(sql, conn);
        await using var reader = await cmd.ExecuteReaderAsync();
        var rows = new List<T>();
        while (await reader.ReadAsync())
            rows.Add(project(reader));
        return rows;
    }

    private static async Task ExecAsync(string connectionString, string sql)
    {
        await using var conn = new NpgsqlConnection(connectionString);
        await conn.OpenAsync();
        await using var cmd = new NpgsqlCommand(sql, conn);
        await cmd.ExecuteNonQueryAsync();
    }
}
