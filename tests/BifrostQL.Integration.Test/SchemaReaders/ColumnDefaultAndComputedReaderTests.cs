using BifrostQL.Core.Model;
using BifrostQL.MySql;
using BifrostQL.Ngsql;
using FluentAssertions;
using Microsoft.Data.SqlClient;
using MySqlConnector;
using Npgsql;
using Xunit;

namespace BifrostQL.Integration.Test.SchemaReaders;

/// <summary>
/// Each schema reader derives <see cref="ColumnDto.HasDefault"/> and
/// <see cref="ColumnDto.IsComputed"/> in its own catalog SQL, so the only proof
/// the SQL is right is a live catalog. One table per dialect spans every shape
/// the derivation must tell apart: NOT NULL without a default (the one column
/// that stays required on insert), NOT NULL with a literal default, a
/// server-generated default expression, an identity/auto-increment key, a
/// nullable plain column, and a generated (computed) column. Only runs when the
/// dialect's BIFROST_TEST_* connection string is set.
/// </summary>
public sealed class ColumnDefaultAndComputedReaderTests
{
    [SkippableFact]
    public async Task Postgres_reader_reports_defaults_and_generated_columns()
    {
        var connString = Environment.GetEnvironmentVariable("BIFROST_TEST_POSTGRES");
        Skip.If(string.IsNullOrEmpty(connString), "BIFROST_TEST_POSTGRES not set");

        var schema = $"bq_dflt_{Guid.NewGuid():N}";
        await using var conn = new NpgsqlConnection(connString);
        await conn.OpenAsync();
        await ExecAsync(conn, $"""
            CREATE SCHEMA {schema};
            CREATE TABLE {schema}.items (
                id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name text NOT NULL,
                status text NOT NULL DEFAULT 'new',
                created_at timestamptz NOT NULL DEFAULT now(),
                note text NULL,
                name_len integer GENERATED ALWAYS AS (length(name)) STORED
            );
            """);
        try
        {
            var data = await new PostgresSchemaReader().ReadSchemaAsync(conn);
            var cols = data.RawColumns.Where(c => c.TableSchema == schema && c.TableName == "items")
                .ToDictionary(c => c.ColumnName);

            AssertFlags(cols);
        }
        finally
        {
            await ExecAsync(conn, $"DROP SCHEMA {schema} CASCADE");
        }
    }

    [SkippableFact]
    public async Task MySql_reader_reports_defaults_and_generated_columns()
    {
        var masterConnString = Environment.GetEnvironmentVariable("BIFROST_TEST_MYSQL");
        Skip.If(string.IsNullOrEmpty(masterConnString), "BIFROST_TEST_MYSQL not set");

        var dbName = $"bq_dflt_{Guid.NewGuid():N}";
        await using (var master = new MySqlConnection(masterConnString))
        {
            await master.OpenAsync();
            await ExecAsync(master, $"CREATE DATABASE `{dbName}`");
        }
        try
        {
            var builder = new MySqlConnectionStringBuilder(masterConnString) { Database = dbName };
            await using var conn = new MySqlConnection(builder.ConnectionString);
            await conn.OpenAsync();
            await ExecAsync(conn, """
                CREATE TABLE items (
                    id INT AUTO_INCREMENT PRIMARY KEY,
                    name VARCHAR(50) NOT NULL,
                    status VARCHAR(20) NOT NULL DEFAULT 'new',
                    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    note VARCHAR(50) NULL,
                    name_len INT GENERATED ALWAYS AS (CHAR_LENGTH(name)) STORED
                );
                """);

            var data = await new MySqlSchemaReader().ReadSchemaAsync(conn);
            var cols = data.RawColumns.Where(c => c.TableName == "items").ToDictionary(c => c.ColumnName);

            AssertFlags(cols);
        }
        finally
        {
            await using var master = new MySqlConnection(masterConnString);
            await master.OpenAsync();
            await ExecAsync(master, $"DROP DATABASE IF EXISTS `{dbName}`");
        }
    }

    [SkippableFact]
    public async Task SqlServer_reader_reports_defaults_and_computed_columns()
    {
        var connString = Environment.GetEnvironmentVariable("BIFROST_TEST_SQLSERVER");
        Skip.If(string.IsNullOrEmpty(connString), "BIFROST_TEST_SQLSERVER not set");

        var schema = $"bq_dflt_{Guid.NewGuid():N}";
        await using var conn = new SqlConnection(connString);
        await conn.OpenAsync();
        await ExecAsync(conn, $"CREATE SCHEMA [{schema}]");
        await ExecAsync(conn, $"""
            CREATE TABLE [{schema}].[items] (
                id int IDENTITY(1,1) PRIMARY KEY,
                name nvarchar(50) NOT NULL,
                status nvarchar(20) NOT NULL DEFAULT 'new',
                created_at datetime2 NOT NULL DEFAULT SYSUTCDATETIME(),
                note nvarchar(50) NULL,
                name_len AS LEN(name),
                row_ver rowversion
            );
            """);
        try
        {
            var data = await new BifrostQL.SqlServer.SqlServerSchemaReader().ReadSchemaAsync(conn);
            var cols = data.RawColumns.Where(c => c.TableSchema == schema && c.TableName == "items")
                .ToDictionary(c => c.ColumnName);

            AssertFlags(cols);
            cols["row_ver"].HasDefault.Should().BeTrue("a rowversion is server-assigned and cannot be inserted");
            cols["row_ver"].IsComputed.Should().BeFalse();
        }
        finally
        {
            await ExecAsync(conn, $"DROP TABLE [{schema}].[items]; DROP SCHEMA [{schema}];");
        }
    }

    private static void AssertFlags(IReadOnlyDictionary<string, ColumnDto> cols)
    {
        cols["name"].HasDefault.Should().BeFalse("NOT NULL with no default: the one insert-required shape");
        cols["name"].IsComputed.Should().BeFalse();
        cols["status"].HasDefault.Should().BeTrue("a literal DEFAULT");
        cols["created_at"].HasDefault.Should().BeTrue("a default expression");
        cols["id"].HasDefault.Should().BeTrue("identity / auto-increment is server-filled");
        cols["note"].HasDefault.Should().BeFalse();
        cols["note"].IsComputed.Should().BeFalse();
        cols["name_len"].IsComputed.Should().BeTrue("a generated column is never a write input");
        foreach (var plain in new[] { "id", "name", "status", "created_at", "note" })
            cols[plain].IsComputed.Should().BeFalse($"{plain} is an ordinary column");
    }

    private static async Task ExecAsync(System.Data.Common.DbConnection conn, string sql)
    {
        await using var cmd = conn.CreateCommand();
        cmd.CommandText = sql;
        await cmd.ExecuteNonQueryAsync();
    }
}
